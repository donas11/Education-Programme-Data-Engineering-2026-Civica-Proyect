-- CREAMOS ROLE PARA INGESTAR
CREATE ROLE IF NOT EXISTS DEV_ROLE_INGEST;

GRANT USAGE
  ON WAREHOUSE PROYECTDE
  TO ROLE DEV_ROLE_INGEST;

GRANT USAGE
  ON DATABASE DEV_BRONZE_BD_MODELOS
  TO ROLE DEV_ROLE_INGEST;

CREATE USER IF NOT EXISTS USR_DLT_PDE
  PASSWORD = SECRET{{'DLT'}}
  DEFAULT_ROLE = DEV_ROLE_INGEST
  DEFAULT_WAREHOUSE = PROYECTDE
  DEFAULT_NAMESPACE = DEV_BRONZE_BD_MODELOS  --MODELOS.RAW
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE DEV_ROLE_INGEST
  TO USER USR_DLT_PDE;

-- CREAMOS ROLE PARA TRANSFORMAR

CREATE ROLE IF NOT EXISTS DEV_ROLE_TRANSFORM;

GRANT USAGE
  ON WAREHOUSE PROYECTDE
  TO ROLE DEV_ROLE_TRANSFORM;

GRANT USAGE
  ON DATABASE DEV_SILVER_BD_MODELOS
  TO ROLE DEV_ROLE_TRANSFORM;

GRANT USAGE
  ON DATABASE DEV_GOLD_BD_MODELOS
  TO ROLE DEV_ROLE_TRANSFORM;

CREATE USER IF NOT EXISTS USR_DBT_PDE
  PASSWORD = SECRET{{'DBT'}}
  DEFAULT_ROLE = DEV_ROLE_TRANSFORM
  DEFAULT_WAREHOUSE = PROYECTDE
  DEFAULT_NAMESPACE = DEV_SILVER_BD_MODELOS --MODELOS.BRONZE
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE DEV_ROLE_TRANSFORM
  TO USER USR_DBT_PDE;
