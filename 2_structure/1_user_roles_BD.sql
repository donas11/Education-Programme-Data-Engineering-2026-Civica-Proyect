-- CREAMOS ROLE PARA INGESTAR
CREATE ROLE IF NOT EXISTS ROLE_INGEST;

GRANT USAGE
  ON WAREHOUSE PROYECTDE
  TO ROLE ROLE_INGEST;

GRANT USAGE
  ON DATABASE MODELOS
  TO ROLE ROLE_INGEST;

CREATE USER IF NOT EXISTS USR_DLT_PDE
  PASSWORD = SECRET{{'DLT'}}
  DEFAULT_ROLE = ROLE_INGEST
  DEFAULT_WAREHOUSE = PROYECTDE
  DEFAULT_NAMESPACE = MODELOS.RAW
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE ROLE_INGEST
  TO USER USR_DLT_PDE;

-- CREAMOS ROLE PARA TRANSFORMAR

CREATE ROLE IF NOT EXISTS ROLE_TRANSFORM;

GRANT USAGE
  ON WAREHOUSE PROYECTDE
  TO ROLE ROLE_TRANSFORM;

GRANT USAGE
  ON DATABASE MODELOS
  TO ROLE ROLE_TRANSFORM;

GRANT USAGE, CREATE TABLE
  ON SCHEMA MODELOS.RAW
  TO ROLE ROLE_TRANSFORM;

GRANT USAGE, CREATE TABLE
  ON SCHEMA MODELOS.BRONZE
  TO ROLE ROLE_TRANSFORM;

GRANT USAGE, CREATE TABLE
  ON SCHEMA MODELOS.SILVER
  TO ROLE ROLE_TRANSFORM;

GRANT USAGE, CREATE TABLE
  ON SCHEMA MODELOS.GOLD
  TO ROLE ROLE_TRANSFORM;

GRANT USAGE, CREATE TABLE
  ON SCHEMA MODELOS.SNAPSHOTS
  TO ROLE ROLE_TRANSFORM;

CREATE USER IF NOT EXISTS USR_DBT_PDE
  PASSWORD = SECRET{{'DBT'}}
  DEFAULT_ROLE = ROLE_TRANSFORM
  DEFAULT_WAREHOUSE = PROYECTDE
  DEFAULT_NAMESPACE = MODELOS.BRONZE
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE ROLE_TRANSFORM
  TO USER USR_DBT_PDE;
