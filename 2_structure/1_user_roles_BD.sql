GRANT ROLE PRO_ROLE_INGEST TO USER USR_DLT_PRO_PDE;  --INGEST PRO  -->  USR_DLT_PRO_PDE

GRANT ROLE DEV_ROLE_TRANSFORM TO USER USR_DBT_PDE; --TRANSFORM DEV -->  USR_DBT_PDE
GRANT ROLE PRE_ROLE_TRANSFORM TO USER USR_DBT_PRE_PDE; --TRANSFORM DEV -->  USR_DBT_PRE_PDE
GRANT ROLE PRO_ROLE_TRANSFORM TO USER USR_DBT_PRO_PDE; --TRANSFORM DEV -->  USR_DBT_PRO_PDE